import logging
from .utils import append_llm_output
from .feature import Feature, FeaturePool
from .prompts.feature_generation_prompt import prompt_feature_gen

class FeatureGenerator:
    def __init__(self,policy, feature_pool: FeaturePool, llm):
        self.feature_pool = feature_pool
        self.policy = policy
        self.llm = llm
        self.logger = logging.getLogger(self.__class__.__name__)

    def generate_new_features(self):
        
        annotated_screenshot_path = self.policy.current_state.generate_annotated_screenshot()
        self.logger.info("Thinking about what feature to explore next with LLM...")
        activity_list = ";".join([act.split('.')[-1] for act in self.policy.app.activities]) if hasattr(self.policy.app, "activities") else "N/A"
        existing_features = "\n".join([f"- feature description: {f.description}" for f in self.feature_pool.features ])
        prompt = prompt_feature_gen.substitute(activity_list=activity_list,
                                                 app_name=self.policy.app.app_name,
                                                 existing_features=existing_features if existing_features else "N/A")
        response = self.llm.call(prompt, [annotated_screenshot_path])
        raw_response = response
        append_llm_output(stage="generate_new_feature_property", raw_response=raw_response, output_dir=self.policy.device.output_dir, action_count=self.policy.action_count)
        response = self.llm.parse_feature_generation_prompt(response)
        features = response.get("Features", [])
        if len(features) == 0:
            self.logger.info("No new features generated by LLM.")
            return []
        new_features_list = []
        for feature in features:
            new_feature = Feature(
                description=feature["description"],
                widget_label=feature["widget_label"],
                source_activity=self.policy.current_state.foreground_activity.split('.')[-1]
            )
            # Track the triggering widget signature for this feature.
            if feature["widget_label"]-1 >= len(self.policy.current_state.get_actionable_widget_list()):
                self.logger.warning(f"Widget label {feature['widget_label']} out of range for actionable widgets.")
                continue
            act_widget = self.policy.current_state.get_actionable_widget_list()[feature["widget_label"]-1]
            widget_str = self.policy.current_state.get_important_view_hash(act_widget)
            new_feature.widget_str = widget_str
            new_features_list.append(new_feature)
            self.feature_pool.add(new_feature)
            self.policy.widgets_feature_map[widget_str] = len(self.feature_pool.features) - 1
        # self.feature_pool.append_features(new_features_list)
        return new_features_list
    
    def find_next_feature(self):
        new_widgets = [w for w in self.policy.current_state.important_widgets if w not in self.policy.known_widgets]
        if len(new_widgets) > 0:
            self.logger.info(f"Found {len(new_widgets)} new important widgets, generating new features.")
            # Log newly discovered widgets on current screen.
            for w in new_widgets:
                self.logger.info(f"New important widget: {w}")
            new_features = self.generate_new_features()
            if new_features:
                self.logger.info(f"Generated {len(new_features)} new features.")
                # self.feature_pool.append_features(new_features)
                # self.active_feature = new_features[0]
                return new_features[0]
        else:
            # Try existing discovered features that match current activity and widget.
            candidate_features = [f for f in self.feature_pool.get_discovered()]
            for feature in candidate_features:
                if feature.source_activity == self.policy.current_state.foreground_activity.split('.')[-1]:
                    if feature.widget_str in self.policy.current_state.important_widgets:
                        self.logger.info(f"Found existing feature {feature.description} to explore on current screen.")
                        # self.active_feature = feature
                        return feature
        return None
